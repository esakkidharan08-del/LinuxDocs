"""Command-dataset API — authenticated content delivery.

Nobody reads command documentation without an account: every endpoint below
requires a valid access token and responds 401 otherwise (Part 1 of the
improvement plan). Repeat loads stay cheap via ETag revalidation with
Cache-Control: private, no-cache — the browser may store the response but must
revalidate with If-None-Match before reuse, so a signed-out session can never
serve stale content without a round-trip check.

Data originates from backend/data/commands/<slug>.json (per-slug source of
truth); commands.json (aggregate) and commands-index.json (light index) are
generated by backend/scripts/build_commands.mjs. Changes to the source files
require running the pipeline and restarting the service — the dataset is read
once per process.
"""
import hashlib
import json
from pathlib import Path

from flask import Blueprint, Response, jsonify, request
from flask_jwt_extended import jwt_required


commands_bp = Blueprint('commands', __name__)
DATA_PATH = Path(__file__).resolve().parent.parent / 'data'
INDEX_PATH = DATA_PATH / 'commands-index.json'
COMMANDS_PATH = DATA_PATH / 'commands.json'

_index_cache: dict | None = None
_commands_cache: dict[str, dict] | None = None


def load_index() -> dict:
    """Light index: categories, domains, counts + name/summary/tags/slug/category."""
    global _index_cache
    if _index_cache is None:
        _index_cache = json.loads(INDEX_PATH.read_text(encoding='utf-8'))
    return _index_cache


def load_command_map() -> dict[str, dict]:
    """Full documentation entries keyed by slug (lower-cased lookup)."""
    global _commands_cache
    if _commands_cache is None:
        data = json.loads(COMMANDS_PATH.read_text(encoding='utf-8'))
        _commands_cache = {command['slug'].lower(): command for command in data['commands']}
    return _commands_cache


def _etagged(payload: dict) -> Response:
    """Attach a strong ETag derived from the exact payload bytes and honor
    If-None-Match with a body-less 304 (repeat loads cost one request each,
    never a re-download)."""
    raw = json.dumps(payload, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode('utf-8')
    digest = hashlib.sha256(raw).hexdigest()[:32]
    etag = f'"{digest}"'
    headers = {'ETag': etag, 'Cache-Control': 'private, no-cache'}
    for token in request.headers.get('If-None-Match', '').split(','):
        match = token.strip().replace('W/', '').strip('"')
        if match == digest:
            response = Response(status=304)
            response.headers.update(headers)
            return response
    response = jsonify(payload)
    response.headers.update(headers)
    return response


@commands_bp.get('/catalog/index')
@jwt_required()
def catalog_index():
    """Navigation/search index. Requires auth; zero command content beyond
    name/summary/tags/slug/category metadata."""
    return _etagged(load_index())


@commands_bp.get('/commands/<string:slug>')
@jwt_required()
def get_command(slug):
    """Full documentation for one command. Requires auth; 404 for unknown slugs."""
    command = load_command_map().get(slug.lower())
    if command is None:
        return jsonify({'error': 'Command not found'}), 404
    return _etagged({'command': command})
